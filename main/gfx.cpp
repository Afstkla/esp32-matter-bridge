static const int FIRST_GLYPH = 0x20;
static const int GLYPH_SIZE = 8;

static uint16_t *s_frame = nullptr;

void gfxInit(uint16_t *frame) {
  s_frame = frame;
}

void gfxFillScreen(uint16_t colour) {
  uint16_t *p = s_frame;
  for (int i = 0; i < PANEL_W * PANEL_H; i++) {
    *p++ = colour;
  }
}

void gfxFillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t colour) {
  int left = x < 0 ? 0 : x;
  int top = y < 0 ? 0 : y;
  int right = x + w > PANEL_W ? PANEL_W : x + w;
  int bottom = y + h > PANEL_H ? PANEL_H : y + h;
  for (int row = top; row < bottom; row++) {
    uint16_t *p = s_frame + row * PANEL_W + left;
    for (int col = left; col < right; col++) {
      *p++ = colour;
    }
  }
}

void gfxDrawRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t colour) {
  gfxFillRect(x, y, w, 1, colour);
  gfxFillRect(x, y + h - 1, w, 1, colour);
  gfxFillRect(x, y, 1, h, colour);
  gfxFillRect(x + w - 1, y, 1, h, colour);
}

void gfxText(int16_t x, int16_t y, const char *text, uint16_t colour, uint8_t scale) {
  int pen = x;
  for (const char *c = text; *c != '\0'; c++) {
    int index = (uint8_t)*c - FIRST_GLYPH;
    if (index >= 0 && index < (int)(sizeof(FONT8X8) / sizeof(FONT8X8[0]))) {
      for (int row = 0; row < GLYPH_SIZE; row++) {
        uint8_t bits = FONT8X8[index][row];
        for (int col = 0; col < GLYPH_SIZE; col++) {
          if (bits & (1 << col)) {
            gfxFillRect(pen + col * scale, y + row * scale, scale, scale, colour);
          }
        }
      }
    }
    pen += GLYPH_SIZE * scale;
  }
}

int16_t gfxTextWidth(const char *text, uint8_t scale) {
  return (int16_t)(strlen(text) * GLYPH_SIZE * scale);
}
